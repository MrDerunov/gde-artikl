    var lost = n(stats, 'articlesLost');
    var repeats = n(stats, 'repeats');
    var letters = n(stats, 'lettersCaught');
    var loops = n(stats, 'loops');
    var protocols = n(stats, 'protocols');
    var boss = n(stats, 'bossHits');
    if (errors === 0 && saved >= 8) return 'Подозрительно идеальный';
    if (loops >= 5) return 'Мы это уже проходили';
    if (repeats >= 12) return 'Акустический беженец';
    if (letters >= 15) return 'Личный враг профсоюза букв';

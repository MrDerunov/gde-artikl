  /* --- безопасная арифметика статистики -------------------------------- */
  function n(stats, key) {
    var s = stats || {};
    var v = s[key];
    if (typeof v !== 'number' || !isFinite(v) || v < 0) return 0;
    return Math.round(v);
  }
  function countGags(stats) {
    var s = stats || {};
    var k, total = 0;
    for (k in s) {
      if (Object.prototype.hasOwnProperty.call(s, k) && k.indexOf('gag:') === 0) total++;
    }
    return total;
  }

